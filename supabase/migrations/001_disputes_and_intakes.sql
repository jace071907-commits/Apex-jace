  id             bigint generated always as identity primary key,
  domain         text not null,
  pend_id        text,
  inquiry_number text,
  kind           text not null check (kind in ('review', 'status', 'valid', 'invalid')),
  title          text not null,
  message        text,
  is_read        boolean not null default false,
  created_at     timestamptz not null default now()
);
create index if not exists apex_notification_inbox_idx on public.apex_notification (domain, is_read, created_at desc);

create table if not exists public.apex_user_settings (
  domain          text primary key,
  electric_border boolean not null default true,
  accent          text not null default 'blue'
                  check (accent in ('blue', 'violet', 'green', 'orange', 'pink', 'grey')),
  mode            text not null default 'dark' check (mode in ('light', 'dark')),
  orientation     text not null default 'landscape' check (orientation in ('landscape', 'portrait')),
  updated_at      timestamptz not null default now()
);

