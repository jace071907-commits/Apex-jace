create table if not exists public.apex_pend_history (
  id             bigint generated always as identity primary key,
  pend_id        text not null,
  inquiry_number text,
  domain         text,
  action         text not null,
  status         text,
  note           text,
  changed_by     text,
  details        jsonb,
  created_at     timestamptz not null default now()
);
create index if not exists apex_pend_history_domain_idx on public.apex_pend_history (domain, created_at desc);
create index if not exists apex_pend_history_pend_idx   on public.apex_pend_history (pend_id, created_at desc);

