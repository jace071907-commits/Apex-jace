-- ---------------------------------------------------------------------
-- 1. Pend table columns
-- ---------------------------------------------------------------------
alter table public."Pend"
  add column if not exists "id"               bigint generated by default as identity,
  add column if not exists "STATUS"           text default 'Pending',
  add column if not exists "REMARKS"          text,
  add column if not exists "INQUIRY_NUMBER"   text,
  add column if not exists "DATE_PENDED"      date,
  add column if not exists "ASSIGNED_TO"      text,
  add column if not exists "DOMAIN"           text,
  add column if not exists "MANAGER"          text,
  add column if not exists "PENDED_DAYS"      integer default 0,
  add column if not exists "LAST_NOTE"        text,
  add column if not exists "LAST_DATE_UPDATE" date,
  add column if not exists "PEND_REVIEW"      text,
  add column if not exists "REVIEWER"         text,
  add column if not exists "REVIEWER_REMARKS" text,
  add column if not exists "DATE_REVIEWED"    date,
  add column if not exists "ACKNOWLEDGED"     boolean not null default false,
  add column if not exists "ACKNOWLEDGED_BY"  text,
  add column if not exists "ACKNOWLEDGED_AT"  timestamptz,
  add column if not exists "UPDATED_BY"       text,
  add column if not exists "CREATED_AT"       timestamptz not null default now(),
  add column if not exists "UPDATED_AT"       timestamptz not null default now();

create unique index if not exists pend_id_key        on public."Pend" ("id");
create index        if not exists pend_domain_idx    on public."Pend" ("DOMAIN", "DATE_PENDED" desc);
create index        if not exists pend_inquiry_idx   on public."Pend" ("INQUIRY_NUMBER");

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'pend_status_chk') then
    alter table public."Pend" add constraint pend_status_chk
      check ("STATUS" is null or "STATUS" in ('Pending', 'Completed')) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'pend_review_chk') then
    alter table public."Pend" add constraint pend_review_chk
      check ("PEND_REVIEW" is null or "PEND_REVIEW" in ('Valid', 'Invalid')) not valid;
  end if;
end $$;

